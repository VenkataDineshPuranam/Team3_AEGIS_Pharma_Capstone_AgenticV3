# Stage 21 -- the three new payloads all share BatchPayload's exact
# (subject_field, reconciliation_complete, findings) shape; only the subject-id
# field name differs.
_FINDINGS_PAYLOAD_SUBJECT_FIELD = {
    ResearchPayload: "research_id", ClinicalPayload: "protocol_id", RegulatoryPayload: "submission_id",
}


def _build_synthesize_user_prompt(state: GovernedState) -> str:
    payload = state["domain_payload"]
    evidence = [{"evidence_id": e.evidence_id, "status": e.status, "source": e.source} for e in state["evidence"]]

    if isinstance(payload, BatchPayload):
        findings = [f.model_dump() for f in payload.findings]
        body = {"batch_id": payload.batch_id, "findings": findings}
    elif isinstance(payload, PVPayload):
        body = {
            "case_id": payload.case_id, "duplicate_suspected": payload.duplicate_suspected,
            "candidates": [c.model_dump() for c in payload.candidates],
            "normalization_suggestions": [s.model_dump() for s in payload.normalization_suggestions],
        }
    elif isinstance(payload, SupplyPayload):
        body = {"product_id": payload.product_id, "options": [o.model_dump() for o in payload.options]}
    elif type(payload) in _FINDINGS_PAYLOAD_SUBJECT_FIELD:
        subject_field = _FINDINGS_PAYLOAD_SUBJECT_FIELD[type(payload)]
        findings = [f.model_dump() for f in payload.findings]
        body = {subject_field: getattr(payload, subject_field), "findings": findings}
    else:
        raise TypeError(f"_build_synthesize_user_prompt: unrecognized payload type {type(payload)!r}")

    body["available_evidence"] = evidence
    return json.dumps(body)


def _build_critic_user_prompt(state: GovernedState) -> str:
    draft = state["draft_output"]
    evidence_ids = [e.evidence_id for e in state["evidence"]]
    return json.dumps({"draft": draft.model_dump(), "available_evidence_ids": evidence_ids})


def _parse_synthesize_response(text: str) -> DecisionSupportOutput:
    data = json.loads(text.strip().removeprefix("```json").removesuffix("```").strip())
    claims = tuple(Claim(text=c["text"], cites=tuple(c.get("cites", []))) for c in data["claims"])
    return DecisionSupportOutput(summary=data["summary"], claims=claims)


def _parse_critic_response(text: str) -> tuple[str, ReasonCode | None]:
    data = json.loads(text.strip().removeprefix("```json").removesuffix("```").strip())
    verdict = data["verdict"]
    reason_code = ReasonCode(data["reason_code"]) if data.get("reason_code") else None
    if verdict not in ("approve_for_human", "reject"):
        raise ValueError(f"Unrecognized verdict {verdict!r}")
    if verdict == "reject" and reason_code is None:
        # A model that rejects without a reason code violates the critic's own output
        # contract (every reject must carry a reason -- failure_and_loop_guards.md SS4's
        # "no blind retry" rule assumes this). Found live under Groq this session:
        # route_after_critic's routing logic assumes >=1 code exists once verdict != approve
        # -- without this, codes[-1] crashes with IndexError on a genuinely malformed but
        # not-exception-raising response. Treat as the model's own contract violation.
        raise ValueError("verdict='reject' with no reason_code -- critic output contract violation")
    return verdict, reason_code


def _parse_record_chat_response(text: str) -> dict:
    """Parse the Record Assistant's JSON. Unlike synthesize's parser this does not fall
    back to a sentinel on malformed output -- it raises, and record_chat.py turns that
    into an explicit "the assistant could not answer" state. A garbled answer shown as if
    it were a real one is worse than no answer, because the operator has no way to tell
    the difference."""
    data = json.loads(text.strip().removeprefix("```json").removesuffix("```").strip())
    return {
        "summary": str(data.get("summary", "")),
        "answer": str(data.get("answer", "")),
        "next_steps_explanation": str(data.get("next_steps_explanation", "")),
        "cites": [str(c) for c in data.get("cites", [])],
    }


class AnthropicLLM:
    """Route A (ADR-009). Direct Anthropic API in dev/20a; Azure AI Foundry is the
    deployment-time binding behind this same interface (ADR-009 SS"Azure is the
    DEPLOYMENT target")."""

    def __init__(self, model: str | None = None):
        import anthropic

        self._client = anthropic.Anthropic(api_key=os.environ["ANTHROPIC_API_KEY"])
        self._model = model or os.environ.get("ANTHROPIC_MODEL", "claude-sonnet-4-5")

    def _call(self, system: str, user: str) -> tuple[str, int, int]:
        resp = self._client.messages.create(
            model=self._model, max_tokens=1024, system=system,
            messages=[{"role": "user", "content": user}],
        )
        return resp.content[0].text, resp.usage.input_tokens, resp.usage.output_tokens

    def synthesize(self, state: GovernedState) -> tuple[DecisionSupportOutput, int, int]:
        text, tin, tout = self._call(_SYNTHESIZE_SYSTEMS[state["workflow"]], _build_synthesize_user_prompt(state))
        try:
            return _parse_synthesize_response(text), tin, tout
        except (json.JSONDecodeError, KeyError, ValidationError):
            return DecisionSupportOutput(summary="[PARSE_ERROR]", claims=()), tin, tout

    def critic(self, state: GovernedState) -> tuple[str, ReasonCode | None, int, int]:
        text, tin, tout = self._call(_CRITIC_SYSTEMS[state["workflow"]], _build_critic_user_prompt(state))
        try:
            verdict, reason_code = _parse_critic_response(text)
        except (json.JSONDecodeError, KeyError, ValueError):
            verdict, reason_code = "reject", ReasonCode.CONTRACT_VIOLATION
        return verdict, reason_code, tin, tout

    def record_chat(self, user_prompt: str) -> tuple[dict, int, int]:
        text, tin, tout = self._call(_RECORD_CHAT_SYSTEM, user_prompt)
        return _parse_record_chat_response(text), tin, tout


class GroqLLM:
    """Dev-only, provisional (see module docstring). OpenAI-compatible API -- reuses the
    `openai` SDK with Groq's base_url, no new dependency."""

    def __init__(self, model: str | None = None):
        import openai

        self._client = openai.OpenAI(api_key=os.environ["GROQ_API_KEY"], base_url="https://api.groq.com/openai/v1")
        self._model = model or os.environ.get("GROQ_MODEL", "llama-3.1-8b-instant")

    def _call(self, system: str, user: str) -> tuple[str, int, int]:
        resp = self._client.chat.completions.create(
            model=self._model,
            messages=[{"role": "system", "content": system}, {"role": "user", "content": user}],
        )
        text = resp.choices[0].message.content
        usage = resp.usage
        return text, usage.prompt_tokens, usage.completion_tokens

    def synthesize(self, state: GovernedState) -> tuple[DecisionSupportOutput, int, int]:
        text, tin, tout = self._call(_SYNTHESIZE_SYSTEMS[state["workflow"]], _build_synthesize_user_prompt(state))
